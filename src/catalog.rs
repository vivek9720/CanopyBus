pub fn recommended_window(code: &str, hour: u8) -> (i16, u8, u16) {
    let Some(profile) = lookup_crop_profile(code) else {
        return (20, 60, 400);
    };
    let daylight = hour >= 6 && hour <= 20;
    let light = if daylight {
        profile.light_umol
    } else {
        profile.light_umol / 8
    };
    let temp = if daylight {
        profile.temperature_c
    } else {
        profile.temperature_c.saturating_sub(2)
    };
    let humidity = if daylight {
        profile.humidity_low
    } else {
        profile.humidity_high
    };
    (temp, humidity, light)
}

pub fn crop_score(code: &str, temp: i16, humidity: u8, co2: u16) -> i32 {
    let Some(profile) = lookup_crop_profile(code) else {
        return 0;
    };
    let mut score = 100i32;
    score -= (profile.temperature_c as i32 - temp as i32).abs() * 3;
    if humidity < profile.humidity_low {
        score -= (profile.humidity_low - humidity) as i32 * 2;
    }
    if humidity > profile.humidity_high {
        score -= (humidity - profile.humidity_high) as i32 * 2;
    }
    score -= (profile.co2_ppm as i32 - co2 as i32).abs() / 50;
    score
}
