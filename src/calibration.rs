pub fn recipe_for_zone(zone: usize, recurrence: u8) -> ZoneRecipe {
    let idx = zone.wrapping_mul(31).wrapping_add(recurrence as usize * 7) % ZONE_RECIPES.len();
    ZONE_RECIPES[idx]
}

pub fn fan_duty(recipe: ZoneRecipe, temperature: i16) -> u8 {
    let bucket = ((temperature + recipe.temperature_offset).clamp(0, 60) as usize / 10).min(5);
    recipe.fan_curve[bucket]
}

pub fn nutrient_mix(recipe: ZoneRecipe, liters: u16) -> (u32, u32) {
    let a = recipe.nutrient_a as u32 * liters as u32;
    let b = recipe.nutrient_b as u32 * liters as u32;
    (a / 100, b / 100)
}
